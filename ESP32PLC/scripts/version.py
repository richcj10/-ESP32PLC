Import("env")
import os
import subprocess

def _git(*args):
    try:
        r = subprocess.run(
            ["git"] + list(args),
            capture_output=True, text=True,
            cwd=env.subst("$PROJECT_DIR")
        )
        return r.stdout.strip()
    except Exception:
        return ""

fw_ver  = _git("describe", "--tags", "--always", "--dirty") or "dev"
fw_sha  = _git("rev-parse", "--short", "HEAD")              or "0000000"
web_ver = _git("log", "-1", "--format=%h", "--", "data/")  or "0000000"

# Written to a generated header, NOT passed as -D defines. A define lands on
# every compile command, so each commit (and the first edit after one, when
# "-dirty" appears) changed ~150 command lines and forced a full rebuild.
# Only Webportal.cpp includes fw_version.h, so only it recompiles now. The file
# is rewritten only when its text changes, so an unchanged version rebuilds nothing.
gen_dir = os.path.join(env.subst("$PROJECT_BUILD_DIR"), env.subst("$PIOENV"), "generated")
os.makedirs(gen_dir, exist_ok=True)
header = os.path.join(gen_dir, "fw_version.h")
text = (
    "/* Generated by scripts/version.py - do not edit. */\n"
    "#pragma once\n"
    "#define FW_VERSION  \"%s\"\n"
    "#define FW_SHA      \"%s\"\n"
    "#define WEB_VERSION \"%s\"\n" % (fw_ver, fw_sha, web_ver)
)
old = open(header).read() if os.path.isfile(header) else None
if text != old:
    with open(header, "w") as f:
        f.write(text)

env.Append(CPPPATH=[gen_dir])   # constant path — doesn't change between builds

print(f"-- FW version:  {fw_ver}  (sha: {fw_sha})")
print(f"-- Web version: {web_ver}")
